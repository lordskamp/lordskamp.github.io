function freezeSpectra(packId, categories) {
  return Object.freeze(Object.entries(categories).flatMap(([category, rows]) =>
    rows.map(([left, right], index) => Object.freeze({
      id: `${packId}-${category}-${String(index + 1).padStart(2, '0')}`,
      left,
      right,
      category: `${packId}-${category}`
    }))
  ));
}

export const ANIME_SPECTRA = freezeSpectra('anime', anime);
export const GAMES_SPECTRA = freezeSpectra('games', games);

export function getPremiumSpectra(packId) {
  if (packId === 'anime') return ANIME_SPECTRA;
  if (packId === 'games') return GAMES_SPECTRA;
  return null;
}
